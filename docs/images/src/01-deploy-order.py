"""Diagram B — apply order, by Argo CD sync wave.

Every row is one sync wave. The badge is the wave number Argo CD reads from the
annotation, so the picture and `gitops/clusters/base/` cannot drift apart. The
right-hand column is the README step that builds that row.
"""
import sys
import pathlib

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import _draw as d

fig, ax = d.canvas(16.5, 12.6)

d.heading(
    ax,
    "ShopStack · deployment order",
    "Each row is an Argo CD sync wave. Lower waves finish first, so a workload is never "
    "admitted before the CRD, policy and namespace it needs exist.",
)

X = 9.6
W = 58.0
TOP = 9.6
STEP = 6.9
H = 5.7

rows = [
    ("−20", 6, "AppProjects", "shopstack-platform · shopstack-apps",
     "every Application names a project", d.GOLD),
    ("−10", 1, "Namespaces + guard rails",
     "ResourceQuota · LimitRange · default-deny NetworkPolicy · developer RBAC",
     "everything else needs a namespace", d.INK),
    ("0", 2, "CRDs + controllers",
     "Argo Rollouts · ingress-nginx · cert-manager · External Secrets · Kyverno",
     "Rollout, ServiceMonitor, ExternalSecret, policy kinds", d.SLATE),
    ("5", 3, "Admission policies",
     "10 Kyverno ClusterPolicies — Audit in dev and QA, Enforce in production",
     "must exist before the first workload is admitted", d.PLUM),
    ("10", 4, "Observability",
     "kube-prometheus-stack · 4 dashboards · SLO recording rules · 16 alerts",
     "needs the ServiceMonitor and PrometheusRule CRDs", d.MOSS),
    ("20", 5, "Services",
     "catalog · cart · payments · checkout — one Application each",
     "four workloads, their Services, HPAs, PDBs, netpols", d.RUST),
    ("30", 7, "Storefront + TLS + DNS",
     "the only publicly routed workload",
     "needs checkout behind an Ingress and a certificate", d.ACCENT),
]

# The one layer that Argo CD cannot apply to itself.
bootstrap_y = TOP - 1.2
d.card(ax, X, bootstrap_y, W, H, "Bootstrap · Argo CD itself",
       ["helm install argo-cd (pinned chart) · one root Application"],
       d.MUTED, badge="0", dashed=True, title_size=9.4, sub_size=7.2)
ax.text(X + W + 1.8, bootstrap_y + H / 2, "the only imperative step — README step 0",
        fontsize=7.4, color=d.MUTED, va="center", style="italic")

for index, (wave, step, title, detail, why, colour) in enumerate(rows):
    y = bootstrap_y + H + 1.6 + index * STEP
    d.card(ax, X, y, W, H, title, [detail], colour, badge=wave, title_size=9.4, sub_size=7.2)
    ax.text(X + W + 1.8, y + H / 2 - 1.0, f"README step {step}", fontsize=7.4,
            color=d.darken(colour, 0.15), va="center", fontweight="bold")
    ax.text(X + W + 1.8, y + H / 2 + 1.3, why, fontsize=7.2, color=d.MUTED, va="center",
            style="italic")

last_y = bootstrap_y + H + 1.6 + (len(rows) - 1) * STEP
spine_top = bootstrap_y + H / 2
spine_bottom = last_y + H - 1.2

# Time axis: one tick per wave.
ax.plot([4.9, 4.9], [spine_top, spine_bottom], color=d.LINE, linewidth=1.4, zorder=0)
d.arrow(ax, (4.9, spine_bottom - 6.0), (4.9, spine_bottom + 1.0), d.LINE, lw=1.0)
for index in range(len(rows)):
    y = bootstrap_y + H + 1.6 + index * STEP + 1.6
    ax.plot([4.9, X - 0.6], [y, y], color=d.LINE, linewidth=1.0, zorder=0)

ax.text(3.7, (spine_top + spine_bottom) / 2, "apply order", fontsize=7.4, color=d.MUTED,
        rotation=90, va="center", ha="center", fontweight="bold")

# Bottom band: the human command, and what it replaces.
band = last_y + H + 2.6
d.code_block(ax, X, band, 37.0,
             ["# the one command a human runs, once",
              "kubectl apply -f gitops/bootstrap/root-app-prod.yaml"],
             d.INK, size=7.4)
d.code_block(ax, X + 39.0, band, 41.4,
             ["# what GitOps buys you",
              "every later change is a pull request,",
              "and the cluster converges on its own"],
             d.MOSS, size=7.4)

d.footer(
    ax,
    "Waves −20 → 10 are platform machinery; 20 and 30 are the fifteen service Applications "
    "generated by one ApplicationSet.",
    band + 6.6,
)

d.save(fig, "01-deploy-order")
